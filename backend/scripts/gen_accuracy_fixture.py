# 题号重复的两条记录需要共用题号：按题干前缀自动识别，避免硬编码下标
DUPLICATE_MARK = "同一题号"


def build_entries() -> List[Dict[str, object]]:
    """按渲染顺序为每题分配题号（重复题号的两条记录共用同一个题号）。"""
    entries: List[Dict[str, object]] = []
    number = 0
    for index, (fmt, qtype, stem, options, answer) in enumerate(Q, start=1):
        if str(stem).startswith(DUPLICATE_MARK) and entries:
            # 与上一条共用题号，模拟真实文档中的重复编号
            no = entries[-1]["no"]
        else:
            number += 1
            no = number
        entries.append(
            {
                "index": index,
                "no": str(no),
                "fmt": fmt,
                "qtype": qtype,
                "stem": stem,
                "options": list(options),
                "answer": answer,
            }
        )
    return entries


def _answer_text(entry: Dict[str, object]) -> str:
    """把标准答案渲染成文档里的写法。"""
    qtype = entry["qtype"]
    answer = str(entry["answer"])
    if qtype == J:
        return "对" if answer == "√" else "错"
    return answer


def render(entry: Dict[str, object]) -> str:
    """按 fmt 渲染单个题目块。"""
    no = entry["no"]
    fmt = entry["fmt"]
    stem = str(entry["stem"])
    options: List[Tuple[str, str]] = entry["options"]  # type: ignore[assignment]
    answer = _answer_text(entry)

    if fmt == "multiline":
        head = "\n".join(stem.split("|"))
        body = "\n".join(f"{letter}. {text}" for letter, text in options)
        return f"{no}. {head}\n{body}\n答案：{answer}\n"

    if fmt == "inline":
        body = " ".join(f"{letter}.{text}" for letter, text in options)
        return f"{no}. {stem} {body}\n答案：{answer}\n"

    if fmt == "dunhao":
        body = "\n".join(f"{letter}、{text}" for letter, text in options)
        return f"{no}、{stem}\n{body}\n【答案】{answer}\n" if body else f"{no}、{stem}\n【答案】{answer}\n"

    if fmt == "fw":
        body = "\n".join(f"{letter}．{text}" for letter, text in options)
        return f"{no}．{stem}\n{body}\n参考答案:{answer}\n" if body else f"{no}．{stem}\n参考答案:{answer}\n"

    if fmt == "answer_on_last_option":
        lines = []
        for position, (letter, text) in enumerate(options):
            suffix = f" 答案：{answer}" if position == len(options) - 1 else ""
            lines.append(f"{letter}. {text}{suffix}")
        return f"{no}. {stem}\n" + "\n".join(lines) + "\n"

    if fmt == "analysis_same_line":
        body = "\n".join(f"{letter}. {text}" for letter, text in options)
        return f"{no}. {stem}\n{body}\n答案：{answer} 解析：结合临床表现与实验室检查综合判断。\n"

    if fmt == "single_line":
        return f"{no}. {stem} 答案：{answer}\n"

    if fmt == "judge_plain":
        return f"{no}. {stem}\n答案：{answer}\n"

    if fmt == "judge_bracket":
        mark = "正确" if answer == "对" else "错误"
        return f"{no}. {stem}\n【答案】{mark}\n"

    if fmt == "judge_symbol":
        mark = "√" if answer == "对" else "×"
        return f"{no}. {stem}\n答案：{mark}\n"

    if fmt == "noanswer":
        body = "\n".join(f"{letter}. {text}" for letter, text in options)
        return f"{no}. {stem}\n{body}\n"

    if fmt == "two_options":
        body = "\n".join(f"{letter}. {text}" for letter, text in options)
        return f"{no}. {stem}\n{body}\n答案：{answer}\n"

    if fmt == "paren":
        body = "\n".join(f"{letter}. {text}" for letter, text in options)
        return f"（{no}）{stem}\n{body}\n答案：{answer}\n"

    if fmt == "diti":
        body = "\n".join(f"{letter}. {text}" for letter, text in options)
        return f"第{no}题. {stem}\n{body}\n答案：{answer}\n"

    # 默认标准排版
    body = "\n".join(f"{letter}. {text}" for letter, text in options)
    text = f"{no}. {stem}\n"
    if body:
        text += body + "\n"
    return text + f"答案：{answer}\n"


def main() -> None:
    """写出 fixture 与 ground truth。"""
    entries = build_entries()
    assert len(entries) == 100, f"必须正好 100 题，实际 {len(entries)}"

    blocks = ["护理学基础题库（准确率抽检样本 100 题）", ""]
    for entry in entries:
        blocks.append(render(entry))
    TXT_PATH.write_text("\n".join(blocks), encoding="utf-8")

    truth = [
        {
            "no": str(entry["no"]),
            "qtype": entry["qtype"],
            "stem": " ".join(str(entry["stem"]).split("|")),
            "options": {letter: text for letter, text in entry["options"]},  # type: ignore[union-attr]
            "answer": entry["answer"],
        }
        for entry in entries
    ]
    TRUTH_PATH.write_text(
        json.dumps(truth, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    print(f"已生成 {TXT_PATH}（{len(entries)} 题）")
    print(f"已生成 {TRUTH_PATH}")


if __name__ == "__main__":
    main()
